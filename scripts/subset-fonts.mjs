// Core font subsets for the public pages (docs/seo/ACCEPTANCE.md, Gate B).
//
// Every public page downloads Inter (3 weights) and Bricolage Grotesque before the first paint: ~150 KB of fonts
// on a phone. The pages only use printable ASCII and a handful of marks (checked over all sitemap pages on
// 2026-11-13: · U+00B7, U+00A0, U+2011, — U+2014), so this script cuts each font to that CORE set:
//   Inter 400/500/600/700     ~24 KB → ~14 KB each
//   Bricolage (opsz + wght axes kept whole)   77 KB → ~52 KB
// and writes two stylesheets. fonts-core-inter.css (imported by main.css after @fontsource's Inter) declares the
// core faces with a unicode-range; the browser takes the last matching face per character. fonts-core-bricolage.css
// (imported by landing.css INSTEAD of @fontsource's opsz.css) declares every Bricolage face itself, so that no
// character is covered twice (see below). Either way the full @fontsource files are still there, downloaded only
// when a page uses anything else (an é in a name). Nothing changes on screen.
//
//   node scripts/subset-fonts.mjs        (re-run after updating @fontsource or adding a character)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NM = path.join(ROOT, 'node_modules');
const OUT = path.join(ROOT, 'app', 'assets', 'fonts');
fs.mkdirSync(OUT, { recursive: true });

/** The core: printable ASCII plus the marks the copy uses. Keep RANGE and EXTRA in step. */
const EXTRA = '\u00a0\u00b7\u00d7\u2011\u2013\u2014\u2018\u2019\u201c\u201d\u2022\u2026';
const TEXT = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join('') + EXTRA;
const RANGE = 'U+0020-007E,U+00A0,U+00B7,U+00D7,U+2011,U+2013-2014,U+2018-2019,U+201C-201D,U+2022,U+2026';

const fonts = [
  ...[400, 500, 600, 700].map((w) => ({
    src: `@fontsource/inter/files/inter-latin-${w}-normal.woff2`, out: `inter-core-${w}.woff2`,
    face: { family: 'Inter', weight: String(w), format: 'woff2' }, css: 'fonts-core-inter.css',
  })),
  {
    src: '@fontsource-variable/bricolage-grotesque/files/bricolage-grotesque-latin-opsz-normal.woff2', out: 'bricolage-core.woff2',
    // the weight range must equal @fontsource's (200 800): Chrome only combines faces by unicode-range when their
    // descriptors match, and a narrower core face was skipped for the full file (measured 13 Nov)
    face: { family: 'Bricolage Grotesque Variable', weight: '200 800', format: 'woff2-variations' }, css: 'fonts-core-bricolage.css',
  },
];

const HEAD = '/* Generated by scripts/subset-fonts.mjs: do not edit. Import AFTER the @fontsource faces (the last matching face wins). */';
const css = {};
for (const f of fonts) {
  const src = fs.readFileSync(path.join(NM, f.src));
  const out = await subsetFont(src, TEXT, { targetFormat: 'woff2', ...f.opts });
  fs.writeFileSync(path.join(OUT, f.out), out);
  console.log(`${f.out.padEnd(24)} ${String(src.length).padStart(6)} → ${String(out.length).padStart(6)} bytes`);
  (css[f.css] ??= [HEAD]).push(`@font-face{font-family:'${f.face.family}';font-style:normal;font-display:swap;font-weight:${f.face.weight};src:url(../fonts/${f.out}) format('${f.face.format}');unicode-range:${RANGE}}`);
}

// Bricolage: overlapping ranges were not enough. With the core face declared after @fontsource's latin face, Chrome
// still fetched both files (seen 13 Nov). So this file declares ALL of Bricolage's faces itself and gives every
// character exactly one: @fontsource's faces with the core characters taken out of their ranges, then the core.
// landing.css imports this file instead of @fontsource-variable/bricolage-grotesque/opsz.css.
const cp = (h) => parseInt(h, 16);
const hex = (n) => n.toString(16).toUpperCase().padStart(4, '0');
const coreSet = new Set([...TEXT].map((c) => c.codePointAt(0)));
const minusCore = (range) => {
  const out = [];
  for (const part of range.split(',').map((x) => x.trim().replace(/^U\+/i, ''))) {
    const [a, b = a] = part.split('-').map(cp);
    let start = null;
    for (let c = a; c <= b + 1; c++) {
      const keep = c <= b && !coreSet.has(c);
      if (keep && start === null) start = c;
      if (!keep && start !== null) { out.push(start === c - 1 ? `U+${hex(start)}` : `U+${hex(start)}-${hex(c - 1)}`); start = null; }
    }
  }
  return out.join(',');
};
const bdir = '@fontsource-variable/bricolage-grotesque';
const faces = [...fs.readFileSync(path.join(NM, bdir, 'opsz.css'), 'utf8').matchAll(/@font-face\s*{([^}]*)}/g)].map((m) => m[1]);
const lines = [HEAD.replace('Import AFTER the @fontsource faces (the last matching face wins)', 'Replaces @fontsource-variable/bricolage-grotesque/opsz.css')];
for (const body of faces) {
  const file = /url\(\.\/files\/([^)]+)\)/.exec(body)[1];
  const range = minusCore(/unicode-range:\s*([^;]+);/.exec(body)[1]);
  lines.push(`@font-face{font-family:'Bricolage Grotesque Variable';font-style:normal;font-display:swap;font-weight:200 800;src:url(../../../node_modules/${bdir}/files/${file}) format('woff2-variations');unicode-range:${range}}`);
}
lines.push(...css['fonts-core-bricolage.css'].slice(1));
css['fonts-core-bricolage.css'] = lines;

for (const [file, out] of Object.entries(css)) {
  fs.writeFileSync(path.join(ROOT, 'app', 'assets', 'css', file), out.join('\n') + '\n');
  console.log(`wrote app/assets/css/${file}`);
}
